"""Build the reference archetypes (ADL 1.4) and operational templates (OPT 1.4).

The archetypes and the templates are defined once, in content.py. This script writes
the archetypes to models/local/archetypes/<class>/*.adl and each template to
tech/templates/<template-id>/opt/<template-id>.opt, embedding the published openEHR
CKM clusters vendored under models/remote/org.openehr/.

  build.py           write the archetypes and the templates
  build.py --check   write them to a temporary folder and compare with the tree, and
                     verify the vendored CKM files against MANIFEST.txt (offline)
  build.py --sync    fetch the CKM clusters again and rewrite MANIFEST.txt (network)

Python 3.9, standard library only.
"""
import argparse
import filecmp
import hashlib
import pathlib
import sys
import tempfile
import urllib.request

import aom
import content

ROOT = pathlib.Path(__file__).resolve().parents[2]
LOCAL = pathlib.Path("models") / "local" / "archetypes"
TEMPLATES = pathlib.Path("tech") / "templates"
CKM_DIR = ROOT / "models" / "remote" / "org.openehr"
CKM_REST = "https://ckm.openehr.org/ckm/rest/v1/archetypes/%s/%s"

# The published CKM clusters the templates embed: name -> CKM citeable id.
CKM_CLUSTERS = {
    "structured_name": "1013.1.5359",
    "address": "1013.1.273",
    "electronic_communication": "1013.1.5356",
    "person": "1013.1.5358",
    "device": "1013.1.17",
}

META = {
    "author": "openehr-reference-content",
    "date": "2026-11-19",
    "copyright": "© openehr-reference-content contributors",
    "licence": "This work is licensed under the Creative Commons Attribution-ShareAlike 4.0 International License. To view a copy of this license, visit http://creativecommons.org/licenses/by-sa/4.0/.",
    "lifecycle_state": "in_development",
    "opt_lifecycle_state": "Initial",
    "opt_comment": "Operational template generated by openehr-reference-content (https://github.com/Cadasto/openehr-reference-content); CC-BY-SA 4.0",
}


def ckm_file(name, ext):
    return CKM_DIR / "archetypes" / "cluster" / ("openEHR-EHR-CLUSTER.%s.v1.%s" % (name, ext))


def archetype_path(arch):
    """models/local/archetypes/<class>/<archetype-id>.adl: demographic archetypes share
    one folder, as in the CKM mirror; any other archetype has its RM class's folder."""
    kind = "demographic" if "-DEMOGRAPHIC-" in arch.archetype_id else arch.rm_type.lower()
    return LOCAL / kind / (arch.archetype_id + ".adl")


def template_path(template_id):
    return TEMPLATES / template_id / "opt" / (template_id + ".opt")


def build(root):
    """Write every archetype and template below root, at its path in the repository.
    Returns the paths written, relative to root, and the problems found."""
    for name in CKM_CLUSTERS:
        content.CKM[name] = aom.load_ckm_xml(ckm_file(name, "xml"))
    written, problems = [], []
    for arch in content.LOCAL:
        path = archetype_path(arch)
        write(root / path, aom.write_adl(arch, META))
        written.append(path)
    for template_id, uid, concept, make, desc in content.TEMPLATES:
        definition = make()
        aom.close_slots(definition)
        problems += ["%s: %s" % (template_id, p) for p in aom.check_cardinalities(definition)]
        refs = sorted({a.archetype_id for a in aom.roots(definition)})
        d = dict(desc)
        d["references"] = "Archetypes: %s. %s" % (", ".join(refs), definition.archetype.description["references"])
        path = template_path(template_id)
        write(root / path, aom.write_opt(template_id, uid, concept, definition, META, d))
        written.append(path)
    return written, problems


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def manifest():
    lines = {}
    for line in (CKM_DIR / "MANIFEST.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            digest, name = line.split()[:2]
            lines[name] = digest
    return lines


def in_tree():
    """The generated files the repository holds: every archetype under models/local and
    every operational template under tech/templates, relative to the root."""
    files = {p.relative_to(ROOT) for p in (ROOT / LOCAL).rglob("*.adl")}
    files |= {p.relative_to(ROOT) for p in (ROOT / TEMPLATES).glob("*/opt/*.opt")}
    return files


def check():
    failed = False
    pinned = manifest()
    for name in CKM_CLUSTERS:
        for ext in ("adl", "xml"):
            f = ckm_file(name, ext)
            if pinned.get(f.name) != sha256(f):
                print("check: %s does not match MANIFEST.txt" % f.relative_to(ROOT), file=sys.stderr)
                failed = True
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp)
        written, problems = build(out)
        for p in problems:
            print("check: %s" % p, file=sys.stderr)
            failed = True
        generated, tree = set(written), in_tree()
        for f in sorted(generated ^ tree):
            print("check: %s is generated on one side only" % f, file=sys.stderr)
            failed = True
        for f in sorted(generated & tree):
            if not filecmp.cmp(str(out / f), str(ROOT / f), shallow=False):
                print("check: %s differs from what content.py generates; run make generate" % f, file=sys.stderr)
                failed = True
    if not failed:
        print("check: OK, %d CKM files pinned, %d archetypes and %d templates as generated"
              % (2 * len(CKM_CLUSTERS), len(content.LOCAL), len(content.TEMPLATES)))
    return 1 if failed else 0


def sync():
    rows = ["# The published openEHR CKM clusters the templates embed, as CKM exports them.",
            "# Refresh with make sync (network); verify with make check.",
            "# sha256  file  CKM-cid  revision"]
    for name, cid in CKM_CLUSTERS.items():
        for ext in ("adl", "xml"):
            with urllib.request.urlopen(CKM_REST % (cid, ext), timeout=60) as r:
                ckm_file(name, ext).write_bytes(r.read())
        rev = aom.load_ckm_xml(ckm_file(name, "xml")).description.get("revision") or "?"
        for ext in ("adl", "xml"):
            f = ckm_file(name, ext)
            rows.append("%s  %s  %s  %s" % (sha256(f), f.name, cid, rev))
    write(CKM_DIR / "MANIFEST.txt", "\n".join(rows) + "\n")
    print("sync: fetched %d clusters; review the diff, then run make generate" % len(CKM_CLUSTERS))
    return 0


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sync", action="store_true")
    args = ap.parse_args(argv)
    if args.sync:
        return sync()
    if args.check:
        return check()
    _, problems = build(ROOT)
    for p in problems:
        print(p, file=sys.stderr)
    print("generate: wrote %d archetypes under %s and %d templates under %s"
          % (len(content.LOCAL), LOCAL, len(content.TEMPLATES), TEMPLATES))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
